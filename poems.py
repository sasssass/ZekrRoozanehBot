def poem_for(day: date) -> tuple[str, tuple[str, ...]]:
    """The poem belonging to `day`.

    Each pass through the list is shuffled with the pass number as the seed, so
    the order looks random but no poem repeats until every other one has been
    sent.
    """
    passes, position = divmod(day.toordinal(), len(POEMS))
    order = list(range(len(POEMS)))
    random.Random(passes).shuffle(order)
    return POEMS[order[position]]


def format_poem(day: date) -> str:
    poet, lines = poem_for(day)
    body = "\n".join(lines)
    return f"{POEM_TITLE}\n\n{body}\n\n— {poet}"
