def occasions_for(day: date) -> list[str]:
    """Every occasion falling on `day`, lunar ones first."""
    _, hijri_month, hijri_day = gregorian_to_hijri(day)
    _, jalali_month, jalali_day = gregorian_to_jalali(day)

    return [
        *LUNAR_OCCASIONS.get((hijri_month, hijri_day), ()),
        *SOLAR_OCCASIONS.get((jalali_month, jalali_day), ()),
    ]


def format_occasions(day: date) -> str:
    """The occasions block for a message, or an empty string on an ordinary day."""
    occasions = occasions_for(day)
    if not occasions:
        return ""

    lines = "\n".join(f"• {occasion}" for occasion in occasions)
    return f"{OCCASIONS_TITLE}:\n{lines}"


def append_occasions(message: str, day: date) -> str:
    """Add today's occasions under an existing message, when there are any."""
    block = format_occasions(day)
    return f"{message}\n\n{block}" if block else message
